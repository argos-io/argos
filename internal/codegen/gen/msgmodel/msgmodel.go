// Package msgmodel selects and runs message file generation for an IR file.
package msgmodel

import (
	"bytes"
	"fmt"
	"go/format"
	"go/parser"
	"go/token"

	"github.com/argos-io/argos/internal/codegen/gen/message"
	"github.com/argos-io/argos/internal/codegen/ir"
)

// Generate returns message file units for file's message model.
func Generate(file ir.File) ([]ir.Unit, error) {
	switch file.EffectiveMessageModel() {
	case ir.MessageModelNone:
		return nil, nil
	case ir.MessageModelProtobuf:
		return message.GenerateUnits(file)
	default:
		return passThroughUnits(file)
	}
}

func passThroughUnits(file ir.File) ([]ir.Unit, error) {
	out := make([]ir.Unit, len(file.MessageFiles))
	for i, unit := range file.MessageFiles {
		formatted, err := validatePassThroughSource(unit.Source)
		if err != nil {
			return nil, fmt.Errorf("msgmodel: message_files[%d]: %w", i, err)
		}
		out[i] = ir.Unit{
			Name:    unit.Name,
			Source:  formatted,
			Symbols: append([]string(nil), unit.Symbols...),
		}
	}
	return out, nil
}

func validatePassThroughSource(source []byte) ([]byte, error) {
	trimmed := bytes.TrimSpace(source)
	if len(trimmed) == 0 {
		return nil, fmt.Errorf("empty source")
	}
	lines := bytes.Split(trimmed, []byte("\n"))
	first := bytes.TrimSpace(lines[0])
	if !bytes.HasPrefix(first, []byte("// Code generated by")) {
		return nil, fmt.Errorf("source must begin with %q", "// Code generated by")
	}
	fset := token.NewFileSet()
	if _, err := parser.ParseFile(fset, "message.go", trimmed, parser.AllErrors); err != nil {
		return nil, fmt.Errorf("parse: %w", err)
	}
	formatted, err := format.Source(trimmed)
	if err != nil {
		return nil, fmt.Errorf("format: %w", err)
	}
	return formatted, nil
}

// MessageSymbols returns every symbol declared by message units.
func MessageSymbols(units []ir.Unit) []string {
	var out []string
	seen := make(map[string]struct{})
	for _, unit := range units {
		for _, sym := range unit.Symbols {
			if sym == "" {
				continue
			}
			if _, ok := seen[sym]; ok {
				continue
			}
			seen[sym] = struct{}{}
			out = append(out, sym)
		}
	}
	return out
}
