package msgmodel_test

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"

	"github.com/argos-io/argos/internal/codegen/ir"
	"github.com/argos-io/argos/internal/codegen/stub"
)

func TestPassThroughMessageModelGeneratesStubAndMessage(t *testing.T) {
	const msgSource = "// Code generated by test. DO NOT EDIT.\n\npackage attachdemo\n\ntype Ping struct {\n\tMsg string\n}\n"

	file := ir.File{
		GoPackage:    "attachdemo",
		MessageModel: "flatbuffers",
		InputBase:    "ping",
		MessageFiles: []ir.Unit{{
			Name:    "ping.msg.go",
			Source:  []byte(msgSource),
			Symbols: []string{"Ping"},
		}},
		Services: []ir.Service{{
			GoName:   "PingService",
			FullName: "demo.PingService",
			Methods: []ir.Method{{
				GoName:     "Call",
				FullName:   "demo.PingService.Call",
				InputType:  "Ping",
				OutputType: "Ping",
			}},
		}},
	}
	file.Normalize(false)
	if err := file.Validate(false); err != nil {
		t.Fatalf("Validate: %v", err)
	}

	dir := t.TempDir()
	irPath := filepath.Join(dir, "ping.ir.json")
	blob, err := json.Marshal(file)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(irPath, blob, 0o644); err != nil {
		t.Fatal(err)
	}
	outDir := filepath.Join(dir, "gen")
	if err := stub.Run(t.Context(), stub.Options{From: "ir", OutDir: outDir}, []string{irPath}); err != nil {
		t.Fatalf("generate: %v", err)
	}
	if _, err := os.Stat(filepath.Join(outDir, "ping.argos.go")); err != nil {
		t.Fatalf("stub: %v", err)
	}
	if _, err := os.Stat(filepath.Join(outDir, "ping.msg.go")); err != nil {
		t.Fatalf("message: %v", err)
	}
}
