// Package message renders ir.File into *.pb.go or *.msg.go source.
package message

import (
	"fmt"
	"go/format"
	"strings"
	"unicode"

	"github.com/argos-io/argos/internal/codegen/ir"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
)

// Generate returns Go source for message types in file.
func Generate(file ir.File) ([]byte, error) {
	if !file.GenerateMessages() {
		return nil, fmt.Errorf("message: nothing to generate for %s", file.StubName())
	}
	fd, err := fileDescriptor(file)
	if err != nil {
		return nil, err
	}
	if fd.Syntax() != protoreflect.Proto3 {
		return nil, fmt.Errorf("message: syntax %s is not supported; use proto3", fd.Syntax())
	}
	if err := validateDescriptor(newDescriptorInfo(fd)); err != nil {
		return nil, err
	}
	source, err := render(fd, file)
	if err != nil {
		return nil, err
	}
	formatted, err := format.Source(source)
	if err != nil {
		return nil, fmt.Errorf("message: format generated source: %w", err)
	}
	return formatted, nil
}

func render(fd protoreflect.FileDescriptor, file ir.File) ([]byte, error) {
	packageName, err := ir.PackageName(file.GoPackage)
	if err != nil {
		return nil, fmt.Errorf("message: %w", err)
	}
	var b strings.Builder
	ident := fileIdent(fd.Path())
	info := newDescriptorInfo(fd)

	b.WriteString("// Code generated by argos. DO NOT EDIT.\n")
	if src := fd.Path(); src != "" {
		b.WriteString("// source: ")
		b.WriteString(src)
		b.WriteString("\n")
	}
	b.WriteString("\npackage ")
	b.WriteString(packageName)
	b.WriteString("\n\nimport (\n")
	b.WriteString("\tprotoreflect \"google.golang.org/protobuf/reflect/protoreflect\"\n")
	b.WriteString("\tprotoimpl \"google.golang.org/protobuf/runtime/protoimpl\"\n")
	b.WriteString("\treflect \"reflect\"\n")
	b.WriteString("\tsync \"sync\"\n")
	b.WriteString("\tunsafe \"unsafe\"\n")
	b.WriteString(")\n\n")

	for _, enum := range info.enums {
		writeEnum(&b, enum, info, ident)
	}
	for _, msg := range info.generatedMessages() {
		writeMessage(&b, msg, info)
	}

	fdp := protodesc.ToFileDescriptorProto(fd)
	rawDesc, err := proto.Marshal(fdp)
	if err != nil {
		return nil, fmt.Errorf("message: marshal descriptor: %w", err)
	}

	b.WriteString("var File_")
	b.WriteString(ident)
	b.WriteString(" protoreflect.FileDescriptor\n\n")
	writeRawDesc(&b, ident, rawDesc)
	writeMsgTypes(&b, ident, info)
	writeGoTypes(&b, ident, info)
	writeDepIdxs(&b, ident, fd, info)
	writeInit(&b, ident, fd, info, rawDesc)

	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

func validateDescriptor(info *descriptorInfo) error {
	declarations := make(map[string]string)
	declare := func(name, kind string) error {
		if !ir.IsGoIdentifier(name) {
			return fmt.Errorf("message: generated %s name %q is not a valid Go identifier", kind, name)
		}
		if previous, exists := declarations[name]; exists {
			return fmt.Errorf("message: generated %s %q conflicts with %s", kind, name, previous)
		}
		declarations[name] = kind
		return nil
	}
	ident := fileIdent(info.file.Path())
	for _, symbol := range []struct {
		name string
		kind string
	}{
		{"File_" + ident, "file descriptor variable"},
		{"file_" + ident + "_rawDesc", "raw descriptor variable"},
		{"file_" + ident + "_rawDescOnce", "raw descriptor guard"},
		{"file_" + ident + "_rawDescData", "compressed descriptor variable"},
		{"file_" + ident + "_rawDescGZIP", "descriptor helper"},
		{"file_" + ident + "_enumTypes", "enum info variable"},
		{"file_" + ident + "_msgTypes", "message info variable"},
		{"file_" + ident + "_goTypes", "Go types variable"},
		{"file_" + ident + "_depIdxs", "dependency index variable"},
		{"file_" + ident + "_init", "file initializer"},
	} {
		if err := declare(symbol.name, symbol.kind); err != nil {
			return err
		}
	}
	for _, enum := range info.enums {
		if err := declare(info.enumGoName[enum], "enum type"); err != nil {
			return err
		}
		if err := declare(info.enumGoName[enum]+"_name", "enum name map"); err != nil {
			return err
		}
		if err := declare(info.enumGoName[enum]+"_value", "enum value map"); err != nil {
			return err
		}
		for n := 0; n < enum.Values().Len(); n++ {
			if err := declare(enumConstantName(enum, enum.Values().Get(n), info), "enum constant"); err != nil {
				return err
			}
		}
	}
	for _, msg := range info.generatedMessages() {
		if err := declare(info.messageGoName[msg], "message type"); err != nil {
			return err
		}
	}
	for _, msg := range info.messages {
		if msg.IsMapEntry() {
			continue
		}
		fieldNames := make(map[string]struct{}, msg.Fields().Len())
		getterNames := make(map[string]struct{}, msg.Fields().Len())
		for i := 0; i < msg.Fields().Len(); i++ {
			field := msg.Fields().Get(i)
			if oneof := field.ContainingOneof(); oneof != nil && !oneof.IsSynthetic() {
				return fmt.Errorf("message: oneof field %q is not supported", field.FullName())
			}
			fieldName := exportGoName(string(field.Name()))
			if !ir.IsGoIdentifier(fieldName) {
				return fmt.Errorf("message: field %q generates invalid Go identifier %q", field.FullName(), fieldName)
			}
			if _, exists := fieldNames[fieldName]; exists {
				return fmt.Errorf("message: fields in %q generate duplicate Go name %q", msg.FullName(), fieldName)
			}
			fieldNames[fieldName] = struct{}{}
			getterName := "Get" + fieldName
			if _, exists := getterNames[getterName]; exists {
				return fmt.Errorf("message: fields in %q generate duplicate getter %q", msg.FullName(), getterName)
			}
			getterNames[getterName] = struct{}{}
			switch fieldName {
			case "String", "Reset", "ProtoMessage", "ProtoReflect", "Descriptor":
				return fmt.Errorf("message: field %q conflicts with generated method %s", field.FullName(), fieldName)
			}
			if _, err := goFieldType(field, info); err != nil {
				return err
			}
		}
	}
	for i := 0; i < info.file.Services().Len(); i++ {
		service := info.file.Services().Get(i)
		for j := 0; j < service.Methods().Len(); j++ {
			method := service.Methods().Get(j)
			if _, err := info.localMessageType(method.Input()); err != nil {
				return fmt.Errorf("message: RPC %q input: %w", method.FullName(), err)
			}
			if _, err := info.localMessageType(method.Output()); err != nil {
				return fmt.Errorf("message: RPC %q output: %w", method.FullName(), err)
			}
		}
	}
	return nil
}

func writeMessage(b *strings.Builder, msg protoreflect.MessageDescriptor, info *descriptorInfo) {
	goName := info.messageGoName[msg]
	index := info.messageIndex[msg]
	b.WriteString("type ")
	b.WriteString(goName)
	b.WriteString(" struct {\n")
	b.WriteString("\tstate         protoimpl.MessageState `protogen:\"open.v1\"`\n")
	for i := 0; i < msg.Fields().Len(); i++ {
		field := msg.Fields().Get(i)
		b.WriteString("\t")
		b.WriteString(exportGoName(string(field.Name())))
		b.WriteString("\t\t")
		fieldType, _ := goFieldType(field, info)
		b.WriteString(fieldType)
		b.WriteString("\t`")
		b.WriteString(protobufTag(field, info))
		b.WriteString("`\n")
	}
	b.WriteString("\tunknownFields protoimpl.UnknownFields\n")
	b.WriteString("\tsizeCache     protoimpl.SizeCache\n")
	b.WriteString("}\n\n")

	b.WriteString("func (x *")
	b.WriteString(goName)
	b.WriteString(") Reset() {\n\t*x = ")
	b.WriteString(goName)
	b.WriteString("{}\n\tmi := &file_")
	b.WriteString(fileIdent(msg.ParentFile().Path()))
	b.WriteString("_msgTypes[")
	b.WriteString(fmt.Sprint(index))
	b.WriteString("]\n\tms := protoimpl.X.MessageStateOf(protoimpl.Pointer(x))\n\tms.StoreMessageInfo(mi)\n}\n\n")

	b.WriteString("func (x *")
	b.WriteString(goName)
	b.WriteString(") String() string {\n\treturn protoimpl.X.MessageStringOf(x)\n}\n\n")
	b.WriteString("func (*")
	b.WriteString(goName)
	b.WriteString(") ProtoMessage() {}\n\n")

	b.WriteString("func (x *")
	b.WriteString(goName)
	b.WriteString(") ProtoReflect() protoreflect.Message {\n")
	b.WriteString("\tmi := &file_")
	b.WriteString(fileIdent(msg.ParentFile().Path()))
	b.WriteString("_msgTypes[")
	b.WriteString(fmt.Sprint(index))
	b.WriteString("]\n\tif protoimpl.UnsafeEnabled && x != nil {\n")
	b.WriteString("\t\tms := protoimpl.X.MessageStateOf(protoimpl.Pointer(x))\n")
	b.WriteString("\t\tif ms.LoadMessageInfo() == nil {\n")
	b.WriteString("\t\t\tms.StoreMessageInfo(mi)\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\treturn ms\n")
	b.WriteString("\t}\n\treturn mi.MessageOf(x)\n}\n\n")
	b.WriteString("// Deprecated: Use ")
	b.WriteString(goName)
	b.WriteString(".ProtoReflect.Descriptor instead.\n")
	b.WriteString("func (*")
	b.WriteString(goName)
	b.WriteString(") Descriptor() ([]byte, []int) {\n\treturn file_")
	b.WriteString(fileIdent(msg.ParentFile().Path()))
	b.WriteString("_rawDescGZIP(), []int{")
	for i, part := range messagePath(msg) {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(fmt.Sprint(part))
	}
	b.WriteString("}\n}\n\n")

	for i := 0; i < msg.Fields().Len(); i++ {
		field := msg.Fields().Get(i)
		goName := exportGoName(string(field.Name()))
		b.WriteString("func (x *")
		b.WriteString(info.messageGoName[msg])
		b.WriteString(") Get")
		b.WriteString(goName)
		b.WriteString("() ")
		fieldType, _ := goGetterType(field, info)
		b.WriteString(fieldType)
		b.WriteString(" {\n")
		b.WriteString("\tif x != nil")
		if isOptionalScalar(field) {
			b.WriteString(" && x.")
			b.WriteString(goName)
			b.WriteString(" != nil")
		}
		b.WriteString(" {\n\t\treturn ")
		if isOptionalScalar(field) {
			b.WriteString("*x.")
		} else {
			b.WriteString("x.")
		}
		b.WriteString(goName)
		b.WriteString("\n\t}\n")
		b.WriteString("\treturn ")
		b.WriteString(zeroValue(field, info))
		b.WriteString("\n}\n\n")
	}
}

func isOptionalScalar(field protoreflect.FieldDescriptor) bool {
	return field.HasOptionalKeyword() && field.Kind() != protoreflect.MessageKind && field.Kind() != protoreflect.GroupKind
}

func goGetterType(field protoreflect.FieldDescriptor, info *descriptorInfo) (string, error) {
	if isOptionalScalar(field) {
		return goSingleFieldType(field, info)
	}
	return goFieldType(field, info)
}

func writeEnum(b *strings.Builder, enum protoreflect.EnumDescriptor, info *descriptorInfo, ident string) {
	goName := info.enumGoName[enum]
	b.WriteString("type ")
	b.WriteString(goName)
	b.WriteString(" int32\n\n")
	b.WriteString("const (\n")
	for n := 0; n < enum.Values().Len(); n++ {
		value := enum.Values().Get(n)
		b.WriteString("\t")
		b.WriteString(enumConstantName(enum, value, info))
		b.WriteString(" ")
		b.WriteString(goName)
		b.WriteString(" = ")
		b.WriteString(fmt.Sprint(value.Number()))
		b.WriteString("\n")
	}
	b.WriteString(")\n\n")

	b.WriteString("var (\n\t")
	b.WriteString(goName)
	b.WriteString("_name = map[int32]string{\n")
	for n := 0; n < enum.Values().Len(); n++ {
		value := enum.Values().Get(n)
		fmt.Fprintf(b, "\t\t%d: %q,\n", value.Number(), value.Name())
	}
	b.WriteString("\t}\n\t")
	b.WriteString(goName)
	b.WriteString("_value = map[string]int32{\n")
	for n := 0; n < enum.Values().Len(); n++ {
		value := enum.Values().Get(n)
		fmt.Fprintf(b, "\t\t%q: %d,\n", value.Name(), value.Number())
	}
	b.WriteString("\t}\n)\n\n")

	b.WriteString("func (x ")
	b.WriteString(goName)
	b.WriteString(") Enum() *")
	b.WriteString(goName)
	b.WriteString(" {\n\tp := new(")
	b.WriteString(goName)
	b.WriteString(")\n\t*p = x\n\treturn p\n}\n\n")
	b.WriteString("func (x ")
	b.WriteString(goName)
	b.WriteString(") String() string {\n\treturn protoimpl.X.EnumStringOf(x.Descriptor(), protoreflect.EnumNumber(x))\n}\n\n")
	b.WriteString("func (")
	b.WriteString(goName)
	b.WriteString(") Descriptor() protoreflect.EnumDescriptor {\n\treturn file_")
	b.WriteString(ident)
	b.WriteString("_enumTypes[")
	b.WriteString(fmt.Sprint(info.enumIndex[enum]))
	b.WriteString("].Descriptor()\n}\n\n")
	b.WriteString("func (")
	b.WriteString(goName)
	b.WriteString(") Type() protoreflect.EnumType {\n\treturn &file_")
	b.WriteString(ident)
	b.WriteString("_enumTypes[")
	b.WriteString(fmt.Sprint(info.enumIndex[enum]))
	b.WriteString("]\n}\n\n")
	b.WriteString("func (x ")
	b.WriteString(goName)
	b.WriteString(") Number() protoreflect.EnumNumber {\n\treturn protoreflect.EnumNumber(x)\n}\n\n")
	b.WriteString("// Deprecated: Use ")
	b.WriteString(goName)
	b.WriteString(".Descriptor instead.\n")
	b.WriteString("func (")
	b.WriteString(goName)
	b.WriteString(") EnumDescriptor() ([]byte, []int) {\n\treturn file_")
	b.WriteString(ident)
	b.WriteString("_rawDescGZIP(), []int{")
	for n, part := range enumPath(enum) {
		if n > 0 {
			b.WriteString(", ")
		}
		b.WriteString(fmt.Sprint(part))
	}
	b.WriteString("}\n}\n\n")
}

func writeRawDesc(b *strings.Builder, ident string, raw []byte) {
	b.WriteString("var file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc = string([]byte{")
	for i, c := range raw {
		if i > 0 {
			b.WriteString(", ")
		}
		if i%16 == 0 {
			b.WriteString("\n\t")
		}
		fmt.Fprintf(b, "0x%02x", c)
	}
	b.WriteString(",\n})\n\n")

	b.WriteString("var (\n\tfile_")
	b.WriteString(ident)
	b.WriteString("_rawDescOnce sync.Once\n\tfile_")
	b.WriteString(ident)
	b.WriteString("_rawDescData []byte\n)\n\n")

	b.WriteString("func file_")
	b.WriteString(ident)
	b.WriteString("_rawDescGZIP() []byte {\n\tfile_")
	b.WriteString(ident)
	b.WriteString("_rawDescOnce.Do(func() {\n\t\tfile_")
	b.WriteString(ident)
	b.WriteString("_rawDescData = protoimpl.X.CompressGZIP(unsafe.Slice(unsafe.StringData(file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc), len(file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc)))\n\t})\n\treturn file_")
	b.WriteString(ident)
	b.WriteString("_rawDescData\n}\n\n")
}

func writeMsgTypes(b *strings.Builder, ident string, info *descriptorInfo) {
	b.WriteString("var file_")
	b.WriteString(ident)
	b.WriteString("_enumTypes = make([]protoimpl.EnumInfo, ")
	b.WriteString(fmt.Sprint(len(info.enums)))
	b.WriteString(")\n")
	b.WriteString("var file_")
	b.WriteString(ident)
	b.WriteString("_msgTypes = make([]protoimpl.MessageInfo, ")
	b.WriteString(fmt.Sprint(len(info.messages)))
	b.WriteString(")\n")
}

func writeGoTypes(b *strings.Builder, ident string, info *descriptorInfo) {
	b.WriteString("var file_")
	b.WriteString(ident)
	b.WriteString("_goTypes = []any{\n")
	for i, enum := range info.enums {
		b.WriteString("\t(")
		b.WriteString(info.enumGoName[enum])
		b.WriteString(")(0), // ")
		b.WriteString(fmt.Sprint(i))
		b.WriteString(": ")
		b.WriteString(string(enum.FullName()))
		b.WriteString("\n")
	}
	for i, msg := range info.messages {
		b.WriteString("\t")
		if msg.IsMapEntry() {
			b.WriteString("nil")
		} else {
			b.WriteString("(*")
			b.WriteString(info.messageGoName[msg])
			b.WriteString(")(nil)")
		}
		b.WriteString(", // ")
		b.WriteString(fmt.Sprint(len(info.enums) + i))
		b.WriteString(": ")
		b.WriteString(string(msg.FullName()))
		b.WriteString("\n")
	}
	b.WriteString("}\n")
}

func writeDepIdxs(b *strings.Builder, ident string, fd protoreflect.FileDescriptor, info *descriptorInfo) {
	var fields, inputs, outputs []int32
	for _, msg := range info.messages {
		if msg.IsMapEntry() {
			continue
		}
		for i := 0; i < msg.Fields().Len(); i++ {
			field := msg.Fields().Get(i)
			if field.IsMap() {
				index, err := info.messageTypeIndex(field.Message())
				if err == nil {
					fields = append(fields, index)
				}
				continue
			}
			switch field.Kind() {
			case protoreflect.MessageKind, protoreflect.GroupKind:
				index, err := info.messageTypeIndex(field.Message())
				if err == nil {
					fields = append(fields, index)
				}
			case protoreflect.EnumKind:
				index, err := info.enumTypeIndex(field.Enum())
				if err == nil {
					fields = append(fields, index)
				}
			}
		}
	}
	for i := 0; i < fd.Services().Len(); i++ {
		svc := fd.Services().Get(i)
		for j := 0; j < svc.Methods().Len(); j++ {
			method := svc.Methods().Get(j)
			index, err := info.messageTypeIndex(method.Input())
			if err == nil {
				inputs = append(inputs, index)
			}
		}
	}
	for i := 0; i < fd.Services().Len(); i++ {
		svc := fd.Services().Get(i)
		for j := 0; j < svc.Methods().Len(); j++ {
			method := svc.Methods().Get(j)
			index, err := info.messageTypeIndex(method.Output())
			if err == nil {
				outputs = append(outputs, index)
			}
		}
	}
	b.WriteString("var file_")
	b.WriteString(ident)
	b.WriteString("_depIdxs = []int32{\n")
	idx := 0
	for _, v := range fields {
		fmt.Fprintf(b, "\t%d, // %d\n", v, idx)
		idx++
	}
	for _, v := range inputs {
		fmt.Fprintf(b, "\t%d, // %d\n", v, idx)
		idx++
	}
	for _, v := range outputs {
		fmt.Fprintf(b, "\t%d, // %d\n", v, idx)
		idx++
	}
	nField := len(fields)
	nIn := len(inputs)
	nOut := len(outputs)
	fmt.Fprintf(b, "\t%d, // [%d:%d] is the sub-list for method output_type\n", nField+nIn, nField+nIn, nField+nIn+nOut)
	fmt.Fprintf(b, "\t%d, // [%d:%d] is the sub-list for method input_type\n", nField, nField, nField+nIn)
	fmt.Fprintf(b, "\t%d, // [%d:%d] is the sub-list for extension type_name\n", nField+nIn+nOut, nField+nIn+nOut, nField+nIn+nOut)
	fmt.Fprintf(b, "\t%d, // [%d:%d] is the sub-list for extension extendee\n", nField+nIn+nOut, nField+nIn+nOut, nField+nIn+nOut)
	fmt.Fprintf(b, "\t0, // [0:%d] is the sub-list for field type_name\n", nField)
	b.WriteString("}\n\n")
}

func writeInit(b *strings.Builder, ident string, fd protoreflect.FileDescriptor, info *descriptorInfo, rawDesc []byte) {
	b.WriteString("func init() { file_")
	b.WriteString(ident)
	b.WriteString("_init() }\n")
	b.WriteString("func file_")
	b.WriteString(ident)
	b.WriteString("_init() {\n")
	b.WriteString("\tif File_")
	b.WriteString(ident)
	b.WriteString(" != nil {\n\t\treturn\n\t}\n")
	if len(info.generatedMessages()) != 0 {
		b.WriteString("\tif !protoimpl.UnsafeEnabled {\n")
		for _, msg := range info.generatedMessages() {
			index := info.messageIndex[msg]
			b.WriteString("\t\t//lint:ignore SA1019 required for safe-mode protobuf reflection\n")
			b.WriteString("\t\tfile_")
			b.WriteString(ident)
			b.WriteString("_msgTypes[")
			b.WriteString(fmt.Sprint(index))
			b.WriteString("].Exporter = func(v any, i int) any {\n")
			b.WriteString("\t\t\tswitch v := v.(*")
			b.WriteString(info.messageGoName[msg])
			b.WriteString("); i {\n")
			b.WriteString("\t\t\tcase 0:\n\t\t\t\treturn &v.state\n")
			b.WriteString("\t\t\tcase 1:\n\t\t\t\treturn &v.sizeCache\n")
			b.WriteString("\t\t\tcase 2:\n\t\t\t\treturn &v.unknownFields\n")
			b.WriteString("\t\t\tdefault:\n\t\t\t\treturn nil\n\t\t\t}\n\t\t}\n")
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("\ttype x struct{}\n")
	b.WriteString("\tout := protoimpl.TypeBuilder{\n")
	b.WriteString("\t\tFile: protoimpl.DescBuilder{\n")
	b.WriteString("\t\t\tGoPackagePath: reflect.TypeOf(x{}).PkgPath(),\n")
	b.WriteString("\t\t\tRawDescriptor: unsafe.Slice(unsafe.StringData(file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc), len(file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc)),\n")
	b.WriteString("\t\t\tNumEnums:      ")
	b.WriteString(fmt.Sprint(len(info.enums)))
	b.WriteString(",\n")
	b.WriteString("\t\t\tNumMessages:   ")
	b.WriteString(fmt.Sprint(len(info.messages)))
	b.WriteString(",\n")
	b.WriteString("\t\t\tNumExtensions: 0,\n")
	b.WriteString("\t\t\tNumServices:   ")
	b.WriteString(fmt.Sprint(fd.Services().Len()))
	b.WriteString(",\n")
	b.WriteString("\t\t},\n")
	b.WriteString("\t\tGoTypes:           file_")
	b.WriteString(ident)
	b.WriteString("_goTypes,\n")
	b.WriteString("\t\tDependencyIndexes: file_")
	b.WriteString(ident)
	b.WriteString("_depIdxs,\n")
	b.WriteString("\t\tEnumInfos:         file_")
	b.WriteString(ident)
	b.WriteString("_enumTypes,\n")
	b.WriteString("\t\tMessageInfos:      file_")
	b.WriteString(ident)
	b.WriteString("_msgTypes,\n")
	b.WriteString("\t}.Build()\n")
	b.WriteString("\tFile_")
	b.WriteString(ident)
	b.WriteString(" = out.File\n")
	b.WriteString("\tfile_")
	b.WriteString(ident)
	b.WriteString("_goTypes = nil\n")
	b.WriteString("\tfile_")
	b.WriteString(ident)
	b.WriteString("_depIdxs = nil\n")
	b.WriteString("}\n")
}

func fileIdent(path string) string {
	var b strings.Builder
	for _, r := range path {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			b.WriteRune(r)
		default:
			// Encode separators and punctuation instead of folding every
			// character to '_'. Otherwise paths such as a-b.proto and
			// a_b.proto declare the same package-level symbols.
			fmt.Fprintf(&b, "_%x_", r)
		}
	}
	if b.Len() == 0 {
		return "argos_proto"
	}
	return b.String()
}

func zeroValue(field protoreflect.FieldDescriptor, info *descriptorInfo) string {
	if field.IsList() || field.IsMap() || field.Kind() == protoreflect.MessageKind || field.Kind() == protoreflect.GroupKind {
		return "nil"
	}
	switch field.Kind() {
	case protoreflect.StringKind:
		return `""`
	case protoreflect.BytesKind:
		return "nil"
	case protoreflect.BoolKind:
		return "false"
	case protoreflect.EnumKind:
		if field.Enum().Values().Len() > 0 {
			return enumConstantName(field.Enum(), field.Enum().Values().Get(0), info)
		}
		return "0"
	default:
		return "0"
	}
}

func protobufTag(field protoreflect.FieldDescriptor, info *descriptorInfo) string {
	wire := protoWireType(field)
	name := string(field.Name())
	label := "opt"
	if field.IsList() || field.IsMap() {
		label = "rep"
	}
	parts := []string{wire, fmt.Sprint(field.Number()), label}
	if field.IsList() && !field.IsMap() && isPackable(field.Kind()) {
		parts = append(parts, "packed")
	}
	parts = append(parts, "name="+name)
	if jsonName := field.JSONName(); jsonName != name {
		parts = append(parts, "json="+jsonName)
	}
	if field.HasOptionalKeyword() {
		parts = append(parts, "oneof")
	}
	parts = append(parts, "proto3")
	if field.Kind() == protoreflect.EnumKind {
		if enumName, err := info.localEnumType(field.Enum()); err == nil {
			_ = enumName
			parts = append(parts, "enum="+string(field.Enum().FullName()))
		}
	}
	if field.Kind() == protoreflect.MessageKind || field.Kind() == protoreflect.GroupKind {
		if field.Message() != nil && !field.IsMap() {
			parts = append(parts, "msg="+string(field.Message().FullName()))
		}
	}
	jsonTagName := name
	if jsonName := field.JSONName(); jsonName != "" {
		jsonTagName = jsonName
	}
	tag := fmt.Sprintf(`protobuf:"%s" json:"%s,omitempty"`, strings.Join(parts, ","), jsonTagName)
	if field.IsMap() {
		entry := field.Message()
		key := entry.Fields().ByName("key")
		value := entry.Fields().ByName("value")
		tag += fmt.Sprintf(` protobuf_key:"%s" protobuf_val:"%s"`, mapEntryTag(key), mapEntryTag(value))
	}
	return tag
}

func mapEntryTag(field protoreflect.FieldDescriptor) string {
	if field == nil {
		return ""
	}
	return fmt.Sprintf("%s,%d,opt,name=%s,proto3", protoWireType(field), field.Number(), field.Name())
}

func isPackable(kind protoreflect.Kind) bool {
	switch kind {
	case protoreflect.StringKind, protoreflect.BytesKind, protoreflect.MessageKind, protoreflect.GroupKind:
		return false
	default:
		return true
	}
}

func protoWireType(field protoreflect.FieldDescriptor) string {
	switch field.Kind() {
	case protoreflect.StringKind, protoreflect.BytesKind, protoreflect.MessageKind, protoreflect.GroupKind:
		return "bytes"
	case protoreflect.FloatKind, protoreflect.Fixed32Kind, protoreflect.Sfixed32Kind:
		return "fixed32"
	case protoreflect.DoubleKind, protoreflect.Fixed64Kind, protoreflect.Sfixed64Kind:
		return "fixed64"
	default:
		return "varint"
	}
}
