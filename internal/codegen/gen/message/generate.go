// Package message renders ir.File into *.pb.go or *.msg.go source.
package message

import (
	"fmt"
	"strings"
	"unicode"

	"github.com/argos-io/argos/internal/codegen/ir"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
)

// Generate returns Go source for message types in file.
func Generate(file ir.File) ([]byte, error) {
	if !file.GenerateMessages() {
		return nil, fmt.Errorf("message: nothing to generate for %s", file.StubName())
	}
	fd, err := fileDescriptor(file)
	if err != nil {
		return nil, err
	}
	return render(fd, file)
}

func render(fd protoreflect.FileDescriptor, file ir.File) ([]byte, error) {
	var b strings.Builder
	ident := fileIdent(fd.Path())

	b.WriteString("// Code generated by argos. DO NOT EDIT.\n")
	if src := fd.Path(); src != "" {
		b.WriteString("// source: ")
		b.WriteString(src)
		b.WriteString("\n")
	}
	b.WriteString("\npackage ")
	b.WriteString(file.GoPackage)
	b.WriteString("\n\nimport (\n")
	b.WriteString("\tprotoreflect \"google.golang.org/protobuf/reflect/protoreflect\"\n")
	b.WriteString("\tprotoimpl \"google.golang.org/protobuf/runtime/protoimpl\"\n")
	b.WriteString("\treflect \"reflect\"\n")
	b.WriteString("\tsync \"sync\"\n")
	b.WriteString("\tunsafe \"unsafe\"\n")
	b.WriteString(")\n\n")

	messages := topLevelMessages(fd)
	for _, msg := range messages {
		writeMessage(&b, msg)
	}

	fdp := protodesc.ToFileDescriptorProto(fd)
	rawDesc, err := proto.Marshal(fdp)
	if err != nil {
		return nil, fmt.Errorf("message: marshal descriptor: %w", err)
	}

	b.WriteString("var File_")
	b.WriteString(ident)
	b.WriteString(" protoreflect.FileDescriptor\n\n")
	writeRawDesc(&b, ident, rawDesc)
	writeMsgTypes(&b, ident, messages)
	writeGoTypes(&b, ident, messages)
	writeDepIdxs(&b, ident, fd)
	writeInit(&b, ident, fd, messages, rawDesc)

	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

func topLevelMessages(fd protoreflect.FileDescriptor) []protoreflect.MessageDescriptor {
	var out []protoreflect.MessageDescriptor
	for i := 0; i < fd.Messages().Len(); i++ {
		out = append(out, fd.Messages().Get(i))
	}
	return out
}

func writeMessage(b *strings.Builder, msg protoreflect.MessageDescriptor) {
	goName := string(msg.Name())
	b.WriteString("type ")
	b.WriteString(goName)
	b.WriteString(" struct {\n")
	b.WriteString("\tstate         protoimpl.MessageState `protogen:\"open.v1\"`\n")
	for i := 0; i < msg.Fields().Len(); i++ {
		field := msg.Fields().Get(i)
		b.WriteString("\t")
		b.WriteString(exportGoName(string(field.Name())))
		b.WriteString("\t\t")
		b.WriteString(goFieldType(field))
		b.WriteString("\t`")
		b.WriteString(protobufTag(field))
		b.WriteString("`\n")
	}
	b.WriteString("\tunknownFields protoimpl.UnknownFields\n")
	b.WriteString("\tsizeCache     protoimpl.SizeCache\n")
	b.WriteString("}\n\n")

	idx := msg.Index()
	b.WriteString("func (x *")
	b.WriteString(goName)
	b.WriteString(") Reset() {\n\t*x = ")
	b.WriteString(goName)
	b.WriteString("{}\n\tmi := &file_")
	b.WriteString(fileIdent(msg.ParentFile().Path()))
	b.WriteString("_msgTypes[")
	b.WriteString(fmt.Sprint(idx))
	b.WriteString("]\n\tms := protoimpl.X.MessageStateOf(protoimpl.Pointer(x))\n\tms.StoreMessageInfo(mi)\n}\n\n")

	b.WriteString("func (x *")
	b.WriteString(goName)
	b.WriteString(") String() string {\n\treturn protoimpl.X.MessageStringOf(x)\n}\n\n")
	b.WriteString("func (*")
	b.WriteString(goName)
	b.WriteString(") ProtoMessage() {}\n\n")

	b.WriteString("func (x *")
	b.WriteString(goName)
	b.WriteString(") ProtoReflect() protoreflect.Message {\n")
	b.WriteString("\tmi := &file_")
	b.WriteString(fileIdent(msg.ParentFile().Path()))
	b.WriteString("_msgTypes[")
	b.WriteString(fmt.Sprint(idx))
	b.WriteString("]\n\tif x != nil {\n")
	b.WriteString("\t\tms := protoimpl.X.MessageStateOf(protoimpl.Pointer(x))\n")
	b.WriteString("\t\tif ms.LoadMessageInfo() == nil {\n")
	b.WriteString("\t\t\tms.StoreMessageInfo(mi)\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\treturn ms\n")
	b.WriteString("\t}\n\treturn mi.MessageOf(x)\n}\n\n")

	for i := 0; i < msg.Fields().Len(); i++ {
		field := msg.Fields().Get(i)
		if field.IsMap() || field.IsList() {
			continue
		}
		goName := exportGoName(string(field.Name()))
		b.WriteString("func (x *")
		b.WriteString(string(msg.Name()))
		b.WriteString(") Get")
		b.WriteString(goName)
		b.WriteString("() ")
		b.WriteString(singleGoType(field))
		b.WriteString(" {\n\tif x != nil {\n\t\treturn x.")
		b.WriteString(goName)
		b.WriteString("\n\t}\n")
		b.WriteString("\treturn ")
		b.WriteString(zeroValue(field))
		b.WriteString("\n}\n\n")
	}
}

func writeRawDesc(b *strings.Builder, ident string, raw []byte) {
	b.WriteString("var file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc = string([]byte{")
	for i, c := range raw {
		if i > 0 {
			b.WriteString(", ")
		}
		if i%16 == 0 {
			b.WriteString("\n\t")
		}
		fmt.Fprintf(b, "0x%02x", c)
	}
	b.WriteString(",\n})\n\n")

	b.WriteString("var (\n\tfile_")
	b.WriteString(ident)
	b.WriteString("_rawDescOnce sync.Once\n\tfile_")
	b.WriteString(ident)
	b.WriteString("_rawDescData []byte\n)\n\n")

	b.WriteString("func file_")
	b.WriteString(ident)
	b.WriteString("_rawDescGZIP() []byte {\n\tfile_")
	b.WriteString(ident)
	b.WriteString("_rawDescOnce.Do(func() {\n\t\tfile_")
	b.WriteString(ident)
	b.WriteString("_rawDescData = protoimpl.X.CompressGZIP(unsafe.Slice(unsafe.StringData(file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc), len(file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc)))\n\t})\n\treturn file_")
	b.WriteString(ident)
	b.WriteString("_rawDescData\n}\n\n")
}

func writeMsgTypes(b *strings.Builder, ident string, messages []protoreflect.MessageDescriptor) {
	b.WriteString("var file_")
	b.WriteString(ident)
	b.WriteString("_msgTypes = make([]protoimpl.MessageInfo, ")
	b.WriteString(fmt.Sprint(len(messages)))
	b.WriteString(")\n")
}

func writeGoTypes(b *strings.Builder, ident string, messages []protoreflect.MessageDescriptor) {
	b.WriteString("var file_")
	b.WriteString(ident)
	b.WriteString("_goTypes = []any{\n")
	for i, msg := range messages {
		b.WriteString("\t(*")
		b.WriteString(string(msg.Name()))
		b.WriteString(")(nil), // ")
		b.WriteString(fmt.Sprint(i))
		b.WriteString(": ")
		b.WriteString(string(msg.FullName()))
		b.WriteString("\n")
	}
	b.WriteString("}\n")
}

func writeDepIdxs(b *strings.Builder, ident string, fd protoreflect.FileDescriptor) {
	var inputs, outputs []int32
	for i := 0; i < fd.Services().Len(); i++ {
		svc := fd.Services().Get(i)
		for j := 0; j < svc.Methods().Len(); j++ {
			method := svc.Methods().Get(j)
			inputs = append(inputs, int32(method.Input().Index()))
		}
	}
	for i := 0; i < fd.Services().Len(); i++ {
		svc := fd.Services().Get(i)
		for j := 0; j < svc.Methods().Len(); j++ {
			method := svc.Methods().Get(j)
			outputs = append(outputs, int32(method.Output().Index()))
		}
	}
	b.WriteString("var file_")
	b.WriteString(ident)
	b.WriteString("_depIdxs = []int32{\n")
	idx := 0
	for _, v := range inputs {
		fmt.Fprintf(b, "\t%d, // %d\n", v, idx)
		idx++
	}
	for _, v := range outputs {
		fmt.Fprintf(b, "\t%d, // %d\n", v, idx)
		idx++
	}
	nIn := len(inputs)
	nOut := len(outputs)
	fmt.Fprintf(b, "\t%d, // [%d:%d] is the sub-list for method output_type\n", nIn, nIn, nIn+nOut)
	fmt.Fprintf(b, "\t0, // [0:%d] is the sub-list for method input_type\n", nIn)
	b.WriteString("\t0, // [0:0] is the sub-list for extension type_name\n")
	b.WriteString("\t0, // [0:0] is the sub-list for extension extendee\n")
	b.WriteString("\t0, // [0:0] is the sub-list for field type_name\n")
	b.WriteString("}\n\n")
}

func writeInit(b *strings.Builder, ident string, fd protoreflect.FileDescriptor, messages []protoreflect.MessageDescriptor, rawDesc []byte) {
	b.WriteString("func init() { file_")
	b.WriteString(ident)
	b.WriteString("_init() }\n")
	b.WriteString("func file_")
	b.WriteString(ident)
	b.WriteString("_init() {\n")
	b.WriteString("\tif File_")
	b.WriteString(ident)
	b.WriteString(" != nil {\n\t\treturn\n\t}\n")
	b.WriteString("\ttype x struct{}\n")
	b.WriteString("\tout := protoimpl.TypeBuilder{\n")
	b.WriteString("\t\tFile: protoimpl.DescBuilder{\n")
	b.WriteString("\t\t\tGoPackagePath: reflect.TypeOf(x{}).PkgPath(),\n")
	b.WriteString("\t\t\tRawDescriptor: unsafe.Slice(unsafe.StringData(file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc), len(file_")
	b.WriteString(ident)
	b.WriteString("_rawDesc)),\n")
	b.WriteString("\t\t\tNumEnums:      0,\n")
	b.WriteString("\t\t\tNumMessages:   ")
	b.WriteString(fmt.Sprint(len(messages)))
	b.WriteString(",\n")
	b.WriteString("\t\t\tNumExtensions: 0,\n")
	b.WriteString("\t\t\tNumServices:   ")
	b.WriteString(fmt.Sprint(fd.Services().Len()))
	b.WriteString(",\n")
	b.WriteString("\t\t},\n")
	b.WriteString("\t\tGoTypes:           file_")
	b.WriteString(ident)
	b.WriteString("_goTypes,\n")
	b.WriteString("\t\tDependencyIndexes: file_")
	b.WriteString(ident)
	b.WriteString("_depIdxs,\n")
	b.WriteString("\t\tMessageInfos:      file_")
	b.WriteString(ident)
	b.WriteString("_msgTypes,\n")
	b.WriteString("\t}.Build()\n")
	b.WriteString("\tFile_")
	b.WriteString(ident)
	b.WriteString(" = out.File\n")
	b.WriteString("\tfile_")
	b.WriteString(ident)
	b.WriteString("_goTypes = nil\n")
	b.WriteString("\tfile_")
	b.WriteString(ident)
	b.WriteString("_depIdxs = nil\n")
	b.WriteString("}\n")
}

func fileIdent(path string) string {
	var b strings.Builder
	for _, r := range path {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			b.WriteRune(r)
		default:
			b.WriteRune('_')
		}
	}
	if b.Len() == 0 {
		return "argos_proto"
	}
	return b.String()
}

func exportGoName(name string) string {
	if name == "" {
		return name
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

func goFieldType(field protoreflect.FieldDescriptor) string {
	if field.IsList() {
		elem := singleGoType(field)
		return "[]" + elem
	}
	return singleGoType(field)
}

func singleGoType(field protoreflect.FieldDescriptor) string {
	switch field.Kind() {
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BytesKind:
		return "[]byte"
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.EnumKind:
		return string(field.Enum().Name())
	case protoreflect.MessageKind:
		return "*" + string(field.Message().Name())
	default:
		return "any"
	}
}

func zeroValue(field protoreflect.FieldDescriptor) string {
	switch field.Kind() {
	case protoreflect.StringKind:
		return `""`
	case protoreflect.BytesKind:
		return "nil"
	case protoreflect.BoolKind:
		return "false"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind,
		protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "0"
	case protoreflect.EnumKind, protoreflect.MessageKind:
		return "nil"
	default:
		return "nil"
	}
}

func protobufTag(field protoreflect.FieldDescriptor) string {
	wire := protoWireType(field)
	name := string(field.Name())
	label := "opt"
	if field.IsList() {
		label = "rep"
	}
	card := "proto3"
	if field.IsList() {
		return fmt.Sprintf(`protobuf:"%s,%d,%s,name=%s,%s" json:"%s,omitempty"`, wire, field.Number(), label, name, card, name)
	}
	return fmt.Sprintf(`protobuf:"%s,%d,%s,name=%s,%s" json:"%s,omitempty"`, wire, field.Number(), label, name, card, name)
}

func protoWireType(field protoreflect.FieldDescriptor) string {
	switch field.Kind() {
	case protoreflect.StringKind:
		return "bytes"
	case protoreflect.BytesKind:
		return "bytes"
	case protoreflect.BoolKind:
		return "varint"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "varint"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "varint"
	case protoreflect.EnumKind:
		return "varint"
	case protoreflect.MessageKind:
		return "bytes"
	default:
		return "bytes"
	}
}
