// Package stubgen renders ir.File into *.argos.go source.
package stubgen

import (
	"fmt"
	"go/format"
	"strings"
	"unicode"

	"github.com/argos-io/argos/internal/codegen/ir"
)

// Generate returns Go source for one IR file.
func Generate(file ir.File) ([]byte, error) {
	packageName, err := ir.PackageName(file.GoPackage)
	if err != nil {
		return nil, fmt.Errorf("codegen: %w", err)
	}
	if err := ir.ValidateNames(&file); err != nil {
		return nil, fmt.Errorf("codegen: %w", err)
	}
	if file.StubName() == "" {
		return nil, fmt.Errorf("codegen: stub output name is required")
	}
	if len(file.Services) == 0 {
		return nil, fmt.Errorf("codegen: no services in %s", file.StubName())
	}

	for i := range file.Services {
		svc := &file.Services[i]
		if svc.FullName == "" {
			svc.FullName = serviceFullName(file.ProtoPackage, svc.GoName)
		}
		for j := range svc.Methods {
			method := &svc.Methods[j]
			method.NormalizeShape()
			if method.FullName == "" {
				method.FullName = svc.FullName + "." + method.GoName
			}
			if err := validateMethod(*svc, *method); err != nil {
				return nil, err
			}
		}
	}

	var body strings.Builder
	for _, svc := range file.Services {
		writeService(&body, svc)
	}

	var b strings.Builder
	b.WriteString("// Code generated by argos. DO NOT EDIT.\n\n")
	b.WriteString("package ")
	b.WriteString(packageName)
	b.WriteString("\n\n")
	writeImports(&b, body.String())
	b.WriteString(body.String())
	source := []byte(strings.TrimRight(b.String(), "\n") + "\n")
	formatted, err := format.Source(source)
	if err != nil {
		return nil, fmt.Errorf("codegen: format stub: %w\n%s", err, source)
	}
	return formatted, nil
}

// closeMethod is the single method name the generated client interface keeps
// for itself.
const closeMethod = "Close"

// stubImports is every package the generated body may reference, in the
// conventional grouping (standard library first).
var stubImports = []string{
	"context",
	"errors",
	"fmt",
	"io",
	"github.com/argos-io/argos",
	"github.com/argos-io/argos/client",
	"github.com/argos-io/argos/descriptor",
	"github.com/argos-io/argos/filter",
	"github.com/argos-io/argos/metadata",
	"github.com/argos-io/argos/server",
	"github.com/argos-io/argos/status",
	"github.com/argos-io/argos/stream",
}

// writeImports emits only the imports the generated body actually references.
// The set depends on the shapes present: metadata appears only for streaming
// clients, errors/fmt/io/status only for single-response wrappers. Emitting them
// unconditionally produced a file that does not compile for a service whose
// methods are all unary — the most common shape there is.
func writeImports(b *strings.Builder, body string) {
	var std, module []string
	for _, path := range stubImports {
		if !referencesPackage(body, path) {
			continue
		}
		if strings.Contains(path, "/") {
			module = append(module, path)
			continue
		}
		std = append(std, path)
	}
	if len(std)+len(module) == 0 {
		return
	}
	b.WriteString("import (\n")
	for _, path := range std {
		b.WriteString("\t\"" + path + "\"\n")
	}
	if len(std) > 0 && len(module) > 0 {
		b.WriteString("\n")
	}
	for _, path := range module {
		b.WriteString("\t\"" + path + "\"\n")
	}
	b.WriteString(")\n\n")
}

// referencesPackage reports whether body qualifies an identifier with the
// package's name (the last path element), ignoring matches inside larger
// identifiers.
func referencesPackage(body, path string) bool {
	name := path
	if i := strings.LastIndexByte(path, '/'); i >= 0 {
		name = path[i+1:]
	}
	needle := name + "."
	for from := 0; from < len(body); {
		i := strings.Index(body[from:], needle)
		if i < 0 {
			return false
		}
		i += from
		if i == 0 || !isIdentByte(body[i-1]) {
			return true
		}
		from = i + 1
	}
	return false
}

func isIdentByte(c byte) bool {
	return c == '_' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9'
}

func validateMethod(svc ir.Service, method ir.Method) error {
	if method.FullName == "" {
		return fmt.Errorf("codegen: method %s.%s missing FullName", svc.GoName, method.GoName)
	}
	if strings.Contains(method.FullName, "/") {
		return fmt.Errorf("codegen: method FullName %q must be protobuf dotted form", method.FullName)
	}
	// The client stub owns Close (it releases the Client the constructor built),
	// so an RPC of that name would be declared twice with two signatures. Failing
	// here beats emitting a file that does not compile.
	if method.GoName == closeMethod {
		return fmt.Errorf("codegen: service %s has RPC %s: it collides with the generated %sClient.%s; rename the RPC",
			svc.FullName, method.GoName, svc.GoName, closeMethod)
	}
	return nil
}

func writeService(b *strings.Builder, svc ir.Service) {
	writeDescriptors(b, svc)
	writeServerInterface(b, svc)
	writeRegister(b, svc)
	writeStreamServers(b, svc)
	writeClientInterface(b, svc)
	writeClient(b, svc)
	writeStreamClients(b, svc)
}

func writeDescriptors(b *strings.Builder, svc ir.Service) {
	methodIdents := make([]string, len(svc.Methods))
	for i, method := range svc.Methods {
		methodIdents[i] = methodIdent(svc.GoName, method.GoName)
	}

	b.WriteString("var (\n")
	for i, method := range svc.Methods {
		b.WriteString("\t")
		b.WriteString(methodIdents[i])
		b.WriteString(" = descriptor.MustMethod(")
		b.WriteString(strconvQuote(method.FullName))
		b.WriteString(", ")
		b.WriteString(shapeConst(method.Shape))
		b.WriteString(")\n")
	}
	b.WriteString("\t")
	b.WriteString(serviceDescIdent(svc.GoName))
	b.WriteString(" = descriptor.MustService(")
	b.WriteString(strconvQuote(svc.FullName))
	if len(methodIdents) > 0 {
		b.WriteString(",\n")
		for _, id := range methodIdents {
			b.WriteString("\t\t")
			b.WriteString(id)
			b.WriteString(",\n")
		}
		b.WriteString("\t")
	}
	b.WriteString(")\n")
	b.WriteString(")\n\n")
}

func writeServerInterface(b *strings.Builder, svc ir.Service) {
	short := serviceShortName(svc.GoName)
	b.WriteString("// ")
	b.WriteString(svc.GoName)
	b.WriteString("Server implements the ")
	b.WriteString(short)
	b.WriteString(" service.\n")
	b.WriteString("type ")
	b.WriteString(svc.GoName)
	b.WriteString("Server interface {\n")
	for _, method := range svc.Methods {
		writeServerMethod(b, svc, method)
	}
	b.WriteString("}\n\n")

	for _, method := range svc.Methods {
		if !method.ClientStream && !method.ServerStream {
			continue
		}
		streamType := streamServerType(svc.GoName, method.GoName)
		b.WriteString("// ")
		b.WriteString(streamType)
		b.WriteString(" sends and receives messages for a ")
		b.WriteString(method.GoName)
		b.WriteString(" call.\n")
		b.WriteString("type ")
		b.WriteString(streamType)
		b.WriteString(" interface {\n")
		if method.ClientStream {
			b.WriteString("\tRecv() (*")
			b.WriteString(method.InputType)
			b.WriteString(", error)\n")
		}
		if method.ClientStream || method.ServerStream {
			b.WriteString("\tSend(*")
			b.WriteString(method.OutputType)
			b.WriteString(") error\n")
		}
		b.WriteString("}\n\n")
	}
}

func writeServerMethod(b *strings.Builder, svc ir.Service, method ir.Method) {
	switch {
	case !method.ClientStream && !method.ServerStream:
		b.WriteString("\t")
		b.WriteString(method.GoName)
		b.WriteString("(context.Context, *")
		b.WriteString(method.InputType)
		b.WriteString(") (*")
		b.WriteString(method.OutputType)
		b.WriteString(", error)\n")
	case !method.ClientStream && method.ServerStream:
		streamType := streamServerType(svc.GoName, method.GoName)
		b.WriteString("\t")
		b.WriteString(method.GoName)
		b.WriteString("(context.Context, *")
		b.WriteString(method.InputType)
		b.WriteString(", ")
		b.WriteString(streamType)
		b.WriteString(") error\n")
	case method.ClientStream:
		streamType := streamServerType(svc.GoName, method.GoName)
		b.WriteString("\t")
		b.WriteString(method.GoName)
		b.WriteString("(context.Context, ")
		b.WriteString(streamType)
		b.WriteString(") error\n")
	}
}

func writeRegister(b *strings.Builder, svc ir.Service) {
	registerName := "Register" + svc.GoName
	b.WriteString("// ")
	b.WriteString(registerName)
	b.WriteString(" registers ")
	b.WriteString(svc.GoName)
	b.WriteString(" handlers on s. Routing uses descriptor Methods; no method switch is generated.\n")
	b.WriteString("func ")
	b.WriteString(registerName)
	b.WriteString("(s *server.Server, impl ")
	b.WriteString(svc.GoName)
	b.WriteString("Server) error {\n")
	b.WriteString("\treturn s.Register(")
	b.WriteString(serviceDescIdent(svc.GoName))
	b.WriteString(", map[string]filter.Handler{\n")
	for _, method := range svc.Methods {
		b.WriteString("\t\t")
		b.WriteString(strconvQuote(method.GoName))
		b.WriteString(": func(ctx context.Context, _ descriptor.Method, st stream.Stream) error {\n")
		writeHandlerBody(b, svc, method)
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t})\n")
	b.WriteString("}\n\n")
}

func writeHandlerBody(b *strings.Builder, svc ir.Service, method ir.Method) {
	switch {
	case !method.ClientStream && !method.ServerStream:
		b.WriteString("\t\t\tin := new(")
		b.WriteString(method.InputType)
		b.WriteString(")\n")
		b.WriteString("\t\t\tif err := st.Recv(in); err != nil {\n")
		b.WriteString("\t\t\t\treturn err\n")
		b.WriteString("\t\t\t}\n")
		b.WriteString("\t\t\tresp, err := impl.")
		b.WriteString(method.GoName)
		b.WriteString("(ctx, in)\n")
		b.WriteString("\t\t\tif err != nil {\n")
		b.WriteString("\t\t\t\treturn err\n")
		b.WriteString("\t\t\t}\n")
		b.WriteString("\t\t\treturn st.Send(resp)\n")
	case !method.ClientStream && method.ServerStream:
		b.WriteString("\t\t\tin := new(")
		b.WriteString(method.InputType)
		b.WriteString(")\n")
		b.WriteString("\t\t\tif err := st.Recv(in); err != nil {\n")
		b.WriteString("\t\t\t\treturn err\n")
		b.WriteString("\t\t\t}\n")
		wrapper := streamServerStruct(svc.GoName, method.GoName)
		b.WriteString("\t\t\treturn impl.")
		b.WriteString(method.GoName)
		b.WriteString("(ctx, in, &")
		b.WriteString(wrapper)
		b.WriteString("{Stream: st})\n")
	case method.ClientStream:
		wrapper := streamServerStruct(svc.GoName, method.GoName)
		b.WriteString("\t\t\treturn impl.")
		b.WriteString(method.GoName)
		b.WriteString("(ctx, &")
		b.WriteString(wrapper)
		b.WriteString("{Stream: st})\n")
	}
}

func writeStreamServers(b *strings.Builder, svc ir.Service) {
	for _, method := range svc.Methods {
		if !method.ClientStream && !method.ServerStream {
			continue
		}
		wrapper := streamServerStruct(svc.GoName, method.GoName)
		b.WriteString("type ")
		b.WriteString(wrapper)
		b.WriteString(" struct {\n")
		b.WriteString("\tstream.Stream\n")
		b.WriteString("}\n\n")
		if method.ClientStream {
			b.WriteString("func (s *")
			b.WriteString(wrapper)
			b.WriteString(") Recv() (*")
			b.WriteString(method.InputType)
			b.WriteString(", error) {\n")
			b.WriteString("\tin := new(")
			b.WriteString(method.InputType)
			b.WriteString(")\n")
			b.WriteString("\tif err := s.Stream.Recv(in); err != nil {\n")
			b.WriteString("\t\treturn nil, err\n")
			b.WriteString("\t}\n")
			b.WriteString("\treturn in, nil\n")
			b.WriteString("}\n\n")
		}
		if method.ClientStream || method.ServerStream {
			b.WriteString("func (s *")
			b.WriteString(wrapper)
			b.WriteString(") Send(msg *")
			b.WriteString(method.OutputType)
			b.WriteString(") error {\n")
			b.WriteString("\treturn s.Stream.Send(msg)\n")
			b.WriteString("}\n\n")
		}
	}
}

func writeClientInterface(b *strings.Builder, svc ir.Service) {
	short := serviceShortName(svc.GoName)
	b.WriteString("// ")
	b.WriteString(svc.GoName)
	b.WriteString("Client calls the ")
	b.WriteString(short)
	b.WriteString(" service.\n")
	b.WriteString("type ")
	b.WriteString(svc.GoName)
	b.WriteString("Client interface {\n")
	for _, method := range svc.Methods {
		writeClientMethod(b, svc, method)
	}
	b.WriteString("\t// Close closes the Client this stub built, releasing its session pool.\n")
	b.WriteString("\tClose() error\n")
	b.WriteString("}\n\n")

	for _, method := range svc.Methods {
		if !method.ClientStream && !method.ServerStream {
			continue
		}
		streamType := streamClientType(svc.GoName, method.GoName)
		b.WriteString("// ")
		b.WriteString(streamType)
		b.WriteString(" sends and receives messages for a ")
		b.WriteString(method.GoName)
		b.WriteString(" call.\n")
		b.WriteString("type ")
		b.WriteString(streamType)
		b.WriteString(" interface {\n")
		if method.ClientStream {
			b.WriteString("\tSend(*")
			b.WriteString(method.InputType)
			b.WriteString(") error\n")
			b.WriteString("\tHalfClose() error\n")
		}
		if method.ClientStream || method.ServerStream {
			b.WriteString("\tRecv() (*")
			b.WriteString(method.OutputType)
			b.WriteString(", error)\n")
		}
		b.WriteString("\tHeader() (metadata.Metadata, error)\n")
		b.WriteString("\tTrailer() metadata.Metadata\n")
		b.WriteString("\tClose() error\n")
		b.WriteString("}\n\n")
	}
}

func writeClientMethod(b *strings.Builder, svc ir.Service, method ir.Method) {
	switch {
	case !method.ClientStream && !method.ServerStream:
		b.WriteString("\t")
		b.WriteString(method.GoName)
		b.WriteString("(context.Context, *")
		b.WriteString(method.InputType)
		b.WriteString(") (*")
		b.WriteString(method.OutputType)
		b.WriteString(", error)\n")
	case !method.ClientStream && method.ServerStream:
		streamType := streamClientType(svc.GoName, method.GoName)
		b.WriteString("\t")
		b.WriteString(method.GoName)
		b.WriteString("(context.Context, *")
		b.WriteString(method.InputType)
		b.WriteString(") (")
		b.WriteString(streamType)
		b.WriteString(", error)\n")
	case method.ClientStream:
		streamType := streamClientType(svc.GoName, method.GoName)
		b.WriteString("\t")
		b.WriteString(method.GoName)
		b.WriteString("(context.Context) (")
		b.WriteString(streamType)
		b.WriteString(", error)\n")
	}
}

func writeClient(b *strings.Builder, svc ir.Service) {
	clientType := clientStructName(svc.GoName)
	constructor := "New" + svc.GoName + "Client"

	// The service name goes in as a literal rather than a read of the emitted
	// service descriptor, which would tie the constructor to the order the var
	// block is initialized in.
	b.WriteString("// ")
	b.WriteString(constructor)
	b.WriteString(" builds a Client for ")
	b.WriteString(svc.FullName)
	b.WriteString(". The service\n")
	b.WriteString("// name is built in; an explicit argos.WithServiceName overrides it because\n")
	b.WriteString("// later options win. Close closes the Client this stub built.\n")
	b.WriteString("func ")
	b.WriteString(constructor)
	b.WriteString("(opts ...argos.ClientOption) (")
	b.WriteString(svc.GoName)
	b.WriteString("Client, error) {\n")
	b.WriteString("\tc, err := client.New(append([]argos.ClientOption{argos.WithServiceName(")
	b.WriteString(strconvQuote(svc.FullName))
	b.WriteString(")}, opts...)...)\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn &")
	b.WriteString(clientType)
	b.WriteString("{c: c}, nil\n")
	b.WriteString("}\n\n")

	b.WriteString("type ")
	b.WriteString(clientType)
	b.WriteString(" struct {\n")
	b.WriteString("\tc *client.Client\n")
	b.WriteString("}\n\n")

	b.WriteString("func (c *")
	b.WriteString(clientType)
	b.WriteString(") Close() error {\n")
	b.WriteString("\treturn c.c.Close()\n")
	b.WriteString("}\n\n")

	for _, method := range svc.Methods {
		writeClientMethodImpl(b, svc, method, clientType)
	}
}

func writeClientMethodImpl(b *strings.Builder, svc ir.Service, method ir.Method, clientType string) {
	ident := methodIdent(svc.GoName, method.GoName)
	switch {
	case !method.ClientStream && !method.ServerStream:
		writeUnaryClient(b, method, clientType, ident)
	case !method.ClientStream && method.ServerStream:
		writeServerStreamClient(b, svc, method, clientType, ident)
	case method.ClientStream && !method.ServerStream:
		writeClientStreamClient(b, svc, method, clientType, ident)
	case method.ClientStream && method.ServerStream:
		writeBidiClient(b, svc, method, clientType, ident)
	}
}

func writeUnaryClient(b *strings.Builder, method ir.Method, clientType, ident string) {
	b.WriteString("func (c *")
	b.WriteString(clientType)
	b.WriteString(") ")
	b.WriteString(method.GoName)
	b.WriteString("(ctx context.Context, req *")
	b.WriteString(method.InputType)
	b.WriteString(") (rsp *")
	b.WriteString(method.OutputType)
	b.WriteString(", err error) {\n")
	b.WriteString("\tst, err := c.c.Open(ctx, ")
	b.WriteString(ident)
	b.WriteString(")\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\tdefer func() {\n")
	b.WriteString("\t\tif closeErr := st.Close(); err == nil && closeErr != nil {\n")
	b.WriteString("\t\t\trsp, err = nil, closeErr\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}()\n\n")
	b.WriteString("\tif err := st.Send(req); err != nil && !errors.Is(err, stream.ErrSendClosed) {\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\tif err := st.HalfClose(); err != nil && !errors.Is(err, stream.ErrSendClosed) {\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\tcandidate := new(")
	b.WriteString(method.OutputType)
	b.WriteString(")\n")
	b.WriteString("\tif err := st.Recv(candidate); err != nil {\n")
	b.WriteString("\t\tif errors.Is(err, io.EOF) {\n")
	b.WriteString("\t\t\treturn nil, fmt.Errorf(\"%w: expected one response, received zero\", status.ErrCardinality)\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\textra := new(")
	b.WriteString(method.OutputType)
	b.WriteString(")\n")
	b.WriteString("\tswitch err := st.Recv(extra); {\n")
	b.WriteString("\tcase errors.Is(err, io.EOF):\n")
	b.WriteString("\t\treturn candidate, nil\n")
	b.WriteString("\tcase err == nil:\n")
	b.WriteString("\t\treturn nil, fmt.Errorf(\"%w: expected one response, received multiple\", status.ErrCardinality)\n")
	b.WriteString("\tdefault:\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("}\n\n")
}

func writeServerStreamClient(b *strings.Builder, svc ir.Service, method ir.Method, clientType, ident string) {
	streamType := streamClientType(svc.GoName, method.GoName)
	wrapper := streamClientStruct(svc.GoName, method.GoName)
	b.WriteString("func (c *")
	b.WriteString(clientType)
	b.WriteString(") ")
	b.WriteString(method.GoName)
	b.WriteString("(ctx context.Context, req *")
	b.WriteString(method.InputType)
	b.WriteString(") (")
	b.WriteString(streamType)
	b.WriteString(", error) {\n")
	b.WriteString("\tst, err := c.c.Open(ctx, ")
	b.WriteString(ident)
	b.WriteString(")\n")
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\tif err := st.Send(req); err != nil && !errors.Is(err, stream.ErrSendClosed) {\n")
	b.WriteString("\t\t_ = st.Close()\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\tif err := st.HalfClose(); err != nil && !errors.Is(err, stream.ErrSendClosed) {\n")
	b.WriteString("\t\t_ = st.Close()\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn &")
	b.WriteString(wrapper)
	b.WriteString("{call: st}, nil\n")
	b.WriteString("}\n\n")
}

