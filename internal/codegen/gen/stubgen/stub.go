func writeStreamClients(b *strings.Builder, svc ir.Service) {
	for _, method := range svc.Methods {
		if !method.ClientStream && !method.ServerStream {
			continue
		}
		wrapper := streamClientStruct(svc.GoName, method.GoName)
		b.WriteString("type ")
		b.WriteString(wrapper)
		b.WriteString(" struct {\n")
		b.WriteString("\tcall *client.CallStream\n")
		if method.ClientStream && !method.ServerStream {
			b.WriteString("\trecvDone bool\n")
		}
		b.WriteString("}\n\n")

		if method.ClientStream {
			b.WriteString("func (c *")
			b.WriteString(wrapper)
			b.WriteString(") Send(msg *")
			b.WriteString(method.InputType)
			b.WriteString(") error {\n")
			b.WriteString("\terr := c.call.Send(msg)\n")
			b.WriteString("\tif err != nil && !errors.Is(err, stream.ErrSendClosed) {\n")
			b.WriteString("\t\treturn err\n")
			b.WriteString("\t}\n")
			b.WriteString("\treturn nil\n")
			b.WriteString("}\n\n")
			b.WriteString("func (c *")
			b.WriteString(wrapper)
			b.WriteString(") HalfClose() error {\n")
			b.WriteString("\terr := c.call.HalfClose()\n")
			b.WriteString("\tif err != nil && !errors.Is(err, stream.ErrSendClosed) {\n")
			b.WriteString("\t\treturn err\n")
			b.WriteString("\t}\n")
			b.WriteString("\treturn nil\n")
			b.WriteString("}\n\n")
		}

		b.WriteString("func (c *")
		b.WriteString(wrapper)
		b.WriteString(") Recv() (*")
		b.WriteString(method.OutputType)
		b.WriteString(", error) {\n")
		if method.ClientStream && !method.ServerStream {
			writeClientStreamRecv(b, method)
		} else {
			b.WriteString("\tevent := new(")
			b.WriteString(method.OutputType)
			b.WriteString(")\n")
			b.WriteString("\tif err := c.call.Recv(event); err != nil {\n")
			b.WriteString("\t\treturn nil, err\n")
			b.WriteString("\t}\n")
			b.WriteString("\treturn event, nil\n")
		}
		b.WriteString("}\n\n")

		b.WriteString("func (c *")
		b.WriteString(wrapper)
		b.WriteString(") Header() (metadata.Metadata, error) {\n")
		b.WriteString("\treturn c.call.Header()\n")
		b.WriteString("}\n\n")
		b.WriteString("func (c *")
		b.WriteString(wrapper)
		b.WriteString(") Trailer() metadata.Metadata {\n")
		b.WriteString("\treturn c.call.Trailer()\n")
		b.WriteString("}\n\n")
		b.WriteString("func (c *")
		b.WriteString(wrapper)
		b.WriteString(") Close() error {\n")
		b.WriteString("\treturn c.call.Close()\n")
		b.WriteString("}\n\n")
	}
}

func writeClientStreamRecv(b *strings.Builder, method ir.Method) {
	// Single-response client-streaming: exactly one message then EOF.
	b.WriteString("\tif c.recvDone {\n")
	b.WriteString("\t\treturn nil, io.EOF\n")
	b.WriteString("\t}\n")
	b.WriteString("\tcandidate := new(")
	b.WriteString(method.OutputType)
	b.WriteString(")\n")
	b.WriteString("\tif err := c.call.Recv(candidate); err != nil {\n")
	b.WriteString("\t\tif errors.Is(err, io.EOF) {\n")
	b.WriteString("\t\t\treturn nil, fmt.Errorf(\"%w: expected one response, received zero\", status.ErrCardinality)\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\textra := new(")
	b.WriteString(method.OutputType)
	b.WriteString(")\n")
	b.WriteString("\tswitch err := c.call.Recv(extra); {\n")
	b.WriteString("\tcase errors.Is(err, io.EOF):\n")
	b.WriteString("\t\tc.recvDone = true\n")
	b.WriteString("\t\treturn candidate, nil\n")
	b.WriteString("\tcase err == nil:\n")
	b.WriteString("\t\treturn nil, fmt.Errorf(\"%w: expected one response, received multiple\", status.ErrCardinality)\n")
	b.WriteString("\tdefault:\n")
	b.WriteString("\t\treturn nil, err\n")
	b.WriteString("\t}\n")
}

func methodIdent(serviceGoName, methodGoName string) string {
	return serviceGoName + "_" + methodGoName
}

func serviceDescIdent(serviceGoName string) string {
	return serviceGoName + "Desc"
}

func clientStructName(serviceGoName string) string {
	return lowerFirst(serviceGoName) + "Client"
}

func serviceFullName(protoPackage, goName string) string {
	if protoPackage == "" {
		return goName
	}
	return protoPackage + "." + goName
}

func shapeConst(shape ir.Shape) string {
	switch shape {
	case ir.ServerStreaming:
		return "descriptor.ServerStreaming"
	case ir.ClientStreaming:
		return "descriptor.ClientStreaming"
	case ir.BidiStreaming:
		return "descriptor.BidiStreaming"
	default:
		return "descriptor.Unary"
	}
}

func serviceShortName(serviceGoName string) string {
	return strings.TrimSuffix(serviceGoName, "Service")
}

func streamServerType(serviceGoName, methodGoName string) string {
	return serviceGoName + "_" + methodGoName + "Server"
}

func streamClientType(serviceGoName, methodGoName string) string {
	return serviceGoName + "_" + methodGoName + "Client"
}

func streamServerStruct(serviceGoName, methodGoName string) string {
	return lowerFirst(serviceGoName) + methodGoName + "Server"
}

func streamClientStruct(serviceGoName, methodGoName string) string {
	return lowerFirst(serviceGoName) + methodGoName + "Client"
}

func lowerFirst(name string) string {
	runes := []rune(name)
	if len(runes) != 0 {
		runes[0] = unicode.ToLower(runes[0])
	}
	return string(runes)
}

func strconvQuote(s string) string {
	return fmt.Sprintf("%q", s)
}
